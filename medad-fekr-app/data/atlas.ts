export function getLandById(id: string) {
  return atlas.find((land) => land.id === id);
}

export function getSituationById(id: string) {
  for (const land of atlas) {
    const situation = land.situations.find((item) => item.id === id);

    if (situation) {
      return {
        land,
        situation,
      };
    }
  }

  return undefined;
}
